/**
 * The OaSIS import (docs/architecture/future-cockpit.md § 6, "Skills, and the government's list for your
 * pick of job, as built"): `scripts/import-oasis.mjs` turns four files of the government's OaSIS 2025
 * Version 1.0 dataset, committed as downloaded under data/oasis-2025-v1.0/, into the catalog module
 * lib/engines/oasis/v2026/data.ts. These tests redo the import on every run and refuse a module that
 * isn't exactly what the files make, so nobody can edit the government's list by hand.
 */
import { createHash } from "node:crypto";
import { readFileSync } from "node:fs";
import path from "node:path";
import { describe, expect, it } from "vitest";

import { oasisData } from "@/lib/engines/oasis/v2026/data";
import { buildOasisModule, evenText, OASIS_DATA_DIR, OASIS_FILES, OASIS_MODULE_PATH } from "../scripts/import-oasis.mjs";

const root = process.cwd();
const read = (rel: string) => readFileSync(path.join(root, rel), "utf8");
const committedFiles = () => Object.fromEntries(OASIS_FILES.map((f) => [f.key, read(path.join(OASIS_DATA_DIR, f.name))])) as Record<
  "guide" | "skills" | "knowledge" | "labels",
  string
>;

describe("the import can be redone", () => {
  it("turns the committed files into the committed module, byte for byte", () => {
    // Git may check a file out with Windows line endings; the module is compared as written, line by line.
    expect(buildOasisModule(committedFiles())).toBe(read(OASIS_MODULE_PATH).replace(/\r\n/g, "\n"));
  });

  it("reads the four files the design names, from the dataset on open.canada.ca", () => {
    expect(OASIS_FILES.map((f) => f.name)).toEqual([
      "guide_oasis_2025_v4.0.csv",
      "skills_oasis_2025_v1.1.csv",
      "knowledge_oasis_2025_v.1.1.csv",
      "labels_oasis_2025_v1.1.csv",
    ]);
    for (const f of OASIS_FILES) {
      expect(f.url).toMatch(/^https:\/\/open\.canada\.ca\/data\/dataset\/10ce43bd-fb58-4969-806b-4bffebc87bec\/resource\/[0-9a-f-]+\/download\//);
      expect(f.url.endsWith(`/${f.name}`)).toBe(true);
    }
  });

  it("records each file's SHA-256, of its text with the line endings evened out", () => {
    const files = committedFiles();
    expect(oasisData.files).toEqual(
      OASIS_FILES.map((f) => ({ name: f.name, sha256: createHash("sha256").update(evenText(files[f.key]), "utf8").digest("hex") })),
    );
  });

  it("keeps every rating in the data, zeros included: one digit per skill or knowledge area for each of the 900 jobs", () => {
    expect(oasisData.occupations).toHaveLength(900);
    const skills = oasisData.descriptors.filter((d) => d[1] === "skills").length;
    const knowledge = oasisData.descriptors.filter((d) => d[1] === "knowledge").length;
    expect([skills, knowledge]).toEqual([33, 44]);
    for (const [code, label, s, k] of oasisData.occupations) {
      expect(code).toMatch(/^\d{5}\.\d{2}$/);
      expect(label.trim()).toBe(label);
      expect(s).toMatch(new RegExp(`^[0-5]{${skills}}$`));
      expect(k).toMatch(new RegExp(`^[0-3]{${knowledge}}$`));
    }
    // Cabinetmakers, as the raw row reads (skills in the taxonomy's order, not the file's column order).
    const cabinetmakers = oasisData.occupations.find((o) => o[0] === "72311.00")!;
    expect(cabinetmakers[1]).toBe("Cabinetmakers");
  });

  it("starts with the licence's attribution line and says it is generated", () => {
    const text = read(OASIS_MODULE_PATH);
    expect(text.split(/\r?\n/).slice(0, 12).join("\n")).toContain("Contains information licensed under the Open Government Licence – Canada.");
    expect(text).toContain("Generated by scripts/import-oasis.mjs");
  });
});

// ---- The import's own rules, on tiny invented files -------------------------------------------------

const guide = [
  "﻿Code;Structure Type;Name;Description",
  "F;Category;Skills;Invented.",
  "F.01.c.01;Descriptor;Numeracy;Invented.",
  'F.03.a.01;Descriptor;"Equipment and Tool  Selection	";Invented; with a semicolon.',
  "G;Category;Knowledge;Invented.",
  "G.10.a.01;Descriptor;Building and Construction;Invented.",
  "G.11.a.02;Descriptor;Mathematics ;Invented.",
].join("\r\n");
// Columns in another order than the taxonomy's, one with other capital letters and a trailing space.
const skills = ["﻿Code OaSIS;OaSIS 2021 Labels;Equipment and tool selection;Numeracy ", "99991.00;Invented job one;0;3", "99992.00;Invented job two;5;1"].join("\r\n");
const knowledge = ["Code OaSIS;OaSIS 2021 Labels;Mathematics;Building and Construction", "99991.00;Invented job one;2;0", "99992.00;Invented job two;0;3"].join("\r\n");
const labels = ["OaSIS profile code;Label", "99991.00;Invented job one", "99992.00;Invented job two"].join("\r\n");
const invented = { guide, skills, knowledge, labels };

describe("the import's rules", () => {
  it("orders each list by the taxonomy, matches columns whatever their spacing and capitals, and keeps zeros", () => {
    const module = buildOasisModule(invented);
    expect(module).toContain('["F.01.c.01", "skills", "Numeracy"]');
    expect(module).toContain('["F.03.a.01", "skills", "Equipment and Tool Selection"]');
    expect(module).toContain('["G.10.a.01", "knowledge", "Building and Construction"]');
    // Taxonomy order: Numeracy (F.01) before Equipment (F.03), Building (G.10) before Mathematics (G.11).
    expect(module).toContain('["99991.00", "Invented job one", "30", "02"]');
    expect(module).toContain('["99992.00", "Invented job two", "15", "30"]');
  });

  it("is the same whatever the line endings of the files", () => {
    const lf = Object.fromEntries(Object.entries(invented).map(([k, v]) => [k, v.replace(/\r\n/g, "\n")])) as typeof invented;
    expect(buildOasisModule(lf)).toBe(buildOasisModule(invented));
  });

  it("refuses a column that matches no entry of the taxonomy", () => {
    expect(() => buildOasisModule({ ...invented, skills: skills.replace("Numeracy ", "Juggling") })).toThrow(/"Juggling".*taxonomy/);
  });

  it("refuses a rating outside its file's scale", () => {
    expect(() => buildOasisModule({ ...invented, knowledge: knowledge.replace("99991.00;Invented job one;2;0", "99991.00;Invented job one;4;0") })).toThrow(
      /rating "4".*99991\.00/,
    );
    expect(() => buildOasisModule({ ...invented, skills: skills.replace(";0;3", ";;3") })).toThrow(/rating "".*99991\.00/);
  });

  it("refuses a job that isn't in every file, or a code that isn't a job code", () => {
    expect(() => buildOasisModule({ ...invented, labels: labels.replace("\r\n99992.00;Invented job two", "") })).toThrow(/99992\.00/);
    expect(() => buildOasisModule({ ...invented, labels: labels.replace("99992.00", "9999") })).toThrow(/9999/);
  });
});
