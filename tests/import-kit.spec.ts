/**
 * The research kit's import core, scripts/lib/import-kit.mjs (docs/architecture/research-kit.md § 5.4): per-file
 * text encoding, the licence header from the registry card (credit line with table id and reference period), the
 * pins, --check and --download, and the amber next-release line. The OaSIS importer runs on it; its own test,
 * tests/oasis-import.spec.ts, is unchanged and still rebuilds lib/engines/oasis/v2026/data.ts byte for byte.
 * Here, a small invented importer over a throwaway folder shows the parts OaSIS doesn't use: a Latin-1 file, a
 * table id and period, and a source whose next release has come.
 */
import { mkdirSync, mkdtempSync, readFileSync, readdirSync, rmSync, writeFileSync, existsSync } from "node:fs";
import os from "node:os";
import path from "node:path";
import { afterEach, describe, expect, it, vi } from "vitest";

import { LICENCES, SOURCES } from "@/lib/engines/research-kit/v2026/registry";
import type { SourceCard } from "@/lib/engines/research-kit/v2026/types";
import { validateRegistry } from "@/lib/engines/research-kit/v2026/validate";

import { OASIS_MODULE_PATH } from "../scripts/import-oasis.mjs";
import {
  commentLines,
  creditLine,
  decode,
  defineImport,
  evenText,
  type Importer,
  fingerprint,
  moduleHeader,
  sourceCard,
} from "../scripts/lib/import-kit.mjs";

const root = process.cwd();

describe("text, in each file's own encoding", () => {
  const cafe = "Café;Crème\r\n";
  it("reads UTF-8 with or without a byte-order mark, and the fingerprint is the same either way and with either line ending", () => {
    const withMark = Buffer.concat([Buffer.from([0xef, 0xbb, 0xbf]), Buffer.from(cafe, "utf8")]);
    expect(decode(withMark, "utf-8")).toBe(`﻿${cafe}`);
    expect(decode(Buffer.from(cafe, "utf8"), "utf-8")).toBe(cafe);
    expect(evenText(decode(withMark, "utf-8"))).toBe("Café;Crème\n");
    expect(fingerprint(decode(withMark, "utf-8"))).toBe(fingerprint(cafe.replace("\r\n", "\n")));
  });

  it("reads Latin-1, where é is one byte", () => {
    expect(decode(Buffer.from(cafe, "latin1"), "latin1")).toBe(cafe);
  });

  it("refuses a Latin-1 file declared UTF-8, and a UTF-8 file declared Latin-1, naming the file", () => {
    expect(() => decode(Buffer.from(cafe, "latin1"), "utf-8", "cops.csv")).toThrow(/cops\.csv is declared UTF-8 but isn't valid UTF-8/);
    const marked = Buffer.concat([Buffer.from([0xef, 0xbb, 0xbf]), Buffer.from(cafe, "utf8")]);
    expect(() => decode(marked, "latin1", "wages.csv")).toThrow(/wages\.csv is declared Latin-1 but starts with a UTF-8 byte-order mark/);
    expect(() => decode(Buffer.from(cafe), "utf-16" as "utf-8")).toThrow(/unknown encoding "utf-16"/);
  });
});

describe("the licence header, from the registry card", () => {
  it("is, for OaSIS, the header the committed module already starts with", () => {
    const committed = readFileSync(path.join(root, OASIS_MODULE_PATH), "utf8").replace(/\r\n/g, "\n").split("\n").slice(0, 8);
    const made = moduleHeader(sourceCard("oasis-2025"), {
      note: "Generated by scripts/import-oasis.mjs from the files in data/oasis-2025-v1.0/. Don't edit it by hand: tests/oasis-import.spec.ts rebuilds it on every run and fails on any difference.",
    });
    expect(made).toEqual(committed);
    expect(made[0]).toBe("// Contains information licensed under the Open Government Licence – Canada.");
  });

  it("fills the credit line's table and reference period from the import's inputs, and refuses a line left unfilled", () => {
    const counts = sourceCard("statcan-business-counts");
    expect(creditLine(counts, { tableId: "33-10-1176-01", referencePeriod: "June 2026" })).toBe(
      "Adapted from Statistics Canada, Canadian Business Counts, table 33-10-1176-01, June 2026. This does not constitute an endorsement by Statistics Canada of this product.",
    );
    expect(() => creditLine(counts, { tableId: "33-10-1176-01" })).toThrow(/needs \{period\}/);
    expect(() => creditLine(sourceCard("job-bank-pages"))).toThrow(/no credit line/);
    const header = moduleHeader(counts, { tableId: "33-10-1176-01", referencePeriod: "June 2026", note: "Invented note." });
    expect(header.join("\n")).toContain("Read from table 33-10-1176-01, reference period June 2026.");
    expect(header.join("\n")).toContain(LICENCES["statcan-open-licence"].url);
  });

  it("breaks long lines between words, never wider than 110 characters", () => {
    const lines = commentLines("word ".repeat(80));
    expect(lines.every((l) => l.length <= 110 && l.startsWith("// "))).toBe(true);
    expect(lines.join(" ").replace(/\/\/ /g, "").split(/\s+/).filter(Boolean)).toHaveLength(80);
  });
});

describe("an importer is refused when it doesn't fit the registry", () => {
  const spec = {
    name: "import-planted",
    label: "planted",
    script: "scripts/import-planted.mjs",
    pinsName: "PLANTED_FILES",
    dataDir: "data/planted",
    modulePath: "lib/engines/planted/v2026/data.ts",
    build: () => "",
  };
  const file = { key: "a", name: "guide_oasis_2025_v4.0.csv", sha256: "0".repeat(64), encoding: "utf-8" as const };

  it("for a source the registry has no card for, or one whose access isn't ship", () => {
    expect(() => defineImport({ ...spec, sourceId: "no-such-source", files: [file] })).toThrow(/no card "no-such-source"/);
    expect(() => defineImport({ ...spec, sourceId: "job-bank-pages", files: [file] })).toThrow(/"never-automated", not "ship"/);
  });

  it("for a file that isn't on its card, a pin that isn't a SHA-256, or an unknown encoding", () => {
    expect(() => defineImport({ ...spec, sourceId: "oasis-2025", files: [{ ...file, name: "abilities.csv" }] })).toThrow(/abilities\.csv isn't one of the files/);
    expect(() => defineImport({ ...spec, sourceId: "oasis-2025", files: [{ ...file, sha256: "abc" }] })).toThrow(/isn't a SHA-256/);
    expect(() => defineImport({ ...spec, sourceId: "oasis-2025", files: [{ ...file, encoding: "utf-16" as "utf-8" }] })).toThrow(/unknown encoding/);
  });
});

// ---- A whole run of an invented importer, over a throwaway folder ------------------------------------------

describe("a run", () => {
  let scratch = "";
  afterEach(() => {
    vi.unstubAllGlobals();
    if (scratch) rmSync(scratch, { recursive: true, force: true });
    scratch = "";
  });

  // A Latin-1 file, as some Statistics Canada files are, with a table id and a reference period.
  const latin1 = Buffer.from("Code;Titre\r\n1;Fabrication de meubles et d'armoires de cuisine\r\n2;Coiffure et esthétique\r\n", "latin1");
  const planted: SourceCard = {
    ...sourceCard("statcan-business-counts"),
    id: "planted-counts",
    phase: "now",
    files: [{ name: "counts.csv", url: "https://www150.statcan.gc.ca/n1/tbl/csv/planted.zip" }],
    nextRelease: { date: "2027-02-12", what: "count" },
  };
  const make = (sha256: string): Importer<"counts"> =>
    defineImport(
      {
        name: "import-planted",
        label: "planted",
        script: "scripts/import-planted.mjs",
        pinsName: "PLANTED_FILES",
        sourceId: "planted-counts",
        dataDir: "data/planted",
        modulePath: "lib/engines/planted/v2026/data.ts",
        tableId: "33-10-1176-01",
        referencePeriod: "June 2026",
        files: [{ key: "counts", name: "counts.csv", sha256, encoding: "latin1" }],
        build: (texts: Record<"counts", string>): string => [...importer.header("Invented note."), "", `export const rows = ${JSON.stringify(evenText(texts.counts).trim().split("\n"))};`, ""].join("\n"),
      },
      { cards: [planted] },
    );
  const pin = fingerprint(latin1.toString("latin1"));
  let importer: Importer<"counts"> = make(pin);

  const makeRoot = () => {
    scratch = mkdtempSync(path.join(os.tmpdir(), "import-kit-"));
    mkdirSync(path.join(scratch, "data", "planted"), { recursive: true });
    mkdirSync(path.join(scratch, "lib", "engines", "planted", "v2026"), { recursive: true });
    writeFileSync(path.join(scratch, "data", "planted", "counts.csv"), latin1);
    return scratch;
  };
  const run = async (argv: string[], dir: string, on = "2026-10-20") => {
    const lines: string[] = [];
    const code = await importer.main(argv, { root: dir, log: (line) => lines.push(line), on });
    return { code, said: lines.join("\n") };
  };

  it("plants a card the validator accepts", () => {
    expect(validateRegistry([...SOURCES, planted], LICENCES, "2026-10-20")).toEqual([]);
  });

  it("reads the Latin-1 file, writes the module with its credit line filled, and --check then matches", async () => {
    importer = make(pin);
    const dir = makeRoot();
    expect((await run([], dir)).code).toBe(0);
    const module = readFileSync(path.join(dir, "lib/engines/planted/v2026/data.ts"), "utf8");
    expect(module).toContain("Coiffure et esthétique");
    expect(module).toContain("// Adapted from Statistics Canada, Canadian Business Counts, table 33-10-1176-01, June 2026.");
    expect(await run(["--check"], dir)).toEqual({ code: 0, said: "lib/engines/planted/v2026/data.ts is what the files in data/planted make." });
  });

  it("--check refuses a data file with one changed byte, names it and its pin, and rebuilds nothing", async () => {
    importer = make(pin);
    const dir = makeRoot();
    await run([], dir);
    const changed = Buffer.from(latin1);
    changed[changed.indexOf("1;")] = "3".charCodeAt(0);
    writeFileSync(path.join(dir, "data/planted/counts.csv"), changed);
    const { code, said } = await run(["--check"], dir);
    expect(code).toBe(1);
    expect(said).toContain("data/planted/counts.csv is not the file pinned for it");
    expect(said).toContain(`the pin in PLANTED_FILES (scripts/import-planted.mjs) is ${pin}`);
    expect(said).toContain("don't match their pins, so nothing was rebuilt");
  });

  it("--check refuses a module with one edited line", async () => {
    importer = make(pin);
    const dir = makeRoot();
    await run([], dir);
    const target = path.join(dir, "lib/engines/planted/v2026/data.ts");
    writeFileSync(target, readFileSync(target, "utf8").replace("esthétique", "esthetique"));
    const { code, said } = await run(["--check"], dir);
    expect(code).toBe(1);
    expect(said).toContain("lib/engines/planted/v2026/data.ts is NOT what the files in data/planted make.");
  });

  it("says the amber line once the source's stated next release has come, and not before", async () => {
    importer = make(pin);
    const dir = makeRoot();
    await run([], dir);
    expect((await run(["--check"], dir, "2027-02-11")).said).not.toContain("may be out");
    const after = await run(["--check"], dir, "2027-02-12");
    expect(after.code).toBe(0);
    expect(after.said).toContain("import-planted: A newer count may be out.");
  });

  it("--download writes a Latin-1 file only when it matches its pin", async () => {
    importer = make(pin);
    const dir = makeRoot();
    rmSync(path.join(dir, "data/planted/counts.csv"));
    vi.stubGlobal("fetch", async () => new Response(new Uint8Array(latin1)));
    expect((await run(["--download"], dir)).code).toBe(0);
    expect(readFileSync(path.join(dir, "data/planted/counts.csv")).equals(latin1)).toBe(true);

    rmSync(path.join(dir, "data/planted/counts.csv"));
    vi.stubGlobal("fetch", async () => new Response(new Uint8Array(Buffer.from(latin1.toString("latin1").replace("1;", "9;"), "latin1"))));
    const { code, said } = await run(["--download"], dir);
    expect(code).toBe(1);
    expect(said).toContain("counts.csv is not the file this script expects, so it was not written.");
    expect(said).toContain("update the pinned sha256 for counts.csv in PLANTED_FILES (scripts/import-planted.mjs)");
    expect(existsSync(path.join(dir, "data/planted/counts.csv"))).toBe(false);
    expect(readdirSync(path.join(dir, "data/planted"))).toEqual([]);
  });
});
