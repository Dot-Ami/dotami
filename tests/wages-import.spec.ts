/**
 * Job Bank's published wages (task 25i; research note 25s; the maintainer's K5 B of 2026-10-16 and his word of
 * 2026-10-21 that the build may download the 2025 file, pinned by checksum). `scripts/import-job-bank-wages.mjs`
 * turns the file committed under data/job-bank-wages-2025/ into lib/engines/wages/v2026/data.ts, and the
 * look-ups in lib/engines/wages/v2026/ give back the file's own rows. These tests redo the import, read the
 * rows research 25s quoted, and plant rows to show the level comes from the source code alone and that a
 * missing row is reported missing, never filled from a neighbour.
 */
import { createHash } from "node:crypto";
import { existsSync, mkdirSync, mkdtempSync, readdirSync, readFileSync, rmSync } from "node:fs";
import os from "node:os";
import path from "node:path";
import { afterEach, describe, expect, it, vi } from "vitest";

import { wageData } from "@/lib/engines/wages/v2026/data";
import { createWageLookup, levelOfSourceCode, wages, type WageLookup, type WageRow } from "@/lib/engines/wages/v2026";
import { SOURCES } from "@/lib/engines/research-kit/v2026/registry";
import { buildWageModule, evenText, main, readWageFile, WAGE_DATA_DIR, WAGE_FILES, WAGE_MODULE_PATH } from "../scripts/import-job-bank-wages.mjs";

const root = process.cwd();
const read = (rel: string) => readFileSync(path.join(root, rel), "utf8");
const FILE = WAGE_FILES[0]!;
const committedText = () => read(path.join(WAGE_DATA_DIR, FILE.name));

/** The row a look-up found; fails the test when it found none. */
const rowOf = (lookup: WageLookup): WageRow => {
  if (!lookup.found) throw new Error(`expected a row, got: ${lookup.missing}`);
  return lookup.row;
};

describe("the import can be redone", () => {
  it("turns the committed file into the committed module, byte for byte", () => {
    // Git may check either file out with Windows line endings; the module is compared as written, line by line.
    expect(buildWageModule({ wages: committedText() })).toBe(read(WAGE_MODULE_PATH).replace(/\r\n/g, "\n"));
  });

  it("reads the wage file the registry card names, from the dataset on open.canada.ca, and the card is shipped", () => {
    const card = SOURCES.find((c) => c.id === "job-bank-wages")!;
    expect(card.access).toBe("ship");
    expect(card.phase).toBe("now");
    expect(WAGE_FILES.map((f) => [f.name, f.url, f.encoding])).toEqual([[card.files![0]!.name, card.files![0]!.url, "utf-8"]]);
    expect(FILE.url).toBe(
      "https://open.canada.ca/data/dataset/adad580f-76b0-4502-bd05-20c125de9116/resource/9da94d63-b178-4a64-aeb3-b6a3bd721ad2/download/2a71-das-wage2025opendata-esdc-all-19nov2025-vf.csv",
    );
  });

  it("pins the file's fingerprint in the script, the same SHA-256 the module records", () => {
    const sha256 = createHash("sha256").update(evenText(committedText()), "utf8").digest("hex");
    expect(FILE.sha256).toBe(sha256);
    expect(wageData.file).toEqual({ name: FILE.name, sha256 });
  });

  it("keeps every row of the file, 516 job groups in each of 86 geographies, all revised 2025-11-19", () => {
    expect(wageData.rows).toHaveLength(44376);
    expect(new Set(wageData.rows.map((r) => r[0])).size).toBe(516);
    expect(wageData.geographies).toHaveLength(86);
    expect(wageData.revisionDates).toEqual(["2025-11-19"]);
  });

  it("starts with the licence's attribution line and says it is generated", () => {
    const text = read(WAGE_MODULE_PATH);
    expect(text.split(/\r?\n/).slice(0, 3).join("\n")).toContain("Contains information licensed under the Open Government Licence – Canada.");
    expect(text).toContain("Generated by scripts/import-job-bank-wages.mjs");
  });
});

// ---- The rows research 25s quoted (2025 file, read 2026-10-20) ---------------------------------------

describe("the rows research 25s quoted come back exactly", () => {
  const expected = (row: WageRow) => [row.geography.code, row.geography.name, row.low, row.median, row.high, row.sourceCode, row.level, row.method, row.referencePeriod, row.basis, row.revisionDate, row.comment];

  it("72311 Cabinetmakers: Calgary's economic region and Alberta, each its own Employment Insurance row", () => {
    expect(expected(rowOf(wages.forRegion("72311", "4830")))).toEqual([
      "ER4830", "Calgary", "18", "23", "30", "EI 2023-24 ER NOC5", "economic-region", "Employment Insurance Survey Data", "2023-2024", "hourly", "2025-11-19", "",
    ]);
    expect(expected(rowOf(wages.forProvince("72311", "AB")))).toEqual([
      "ER48", "Alberta", "18", "23", "30", "EI 2023-24 PR NOC5", "province", "Employment Insurance Survey Data", "2023-2024", "hourly", "2025-11-19", "",
    ]);
  });

  it("63210 Hairstylists and barbers: the row under Calgary is an Alberta-wide figure, because its code says PR", () => {
    const calgary = rowOf(wages.forRegion("63210", "ER4830"));
    expect(expected(calgary)).toEqual([
      "ER4830", "Calgary", "15", "19.23", "26", "LFS 2023-24 PR NOC5", "province", "Labour Force Survey", "2023-2024", "hourly", "2025-11-19", "",
    ]);
    // Where it sits is still Calgary's region; what it is, is the province.
    expect(calgary.geography.kind).toBe("economic-region");
    expect(expected(rowOf(wages.forProvince("63210", "AB")))).toEqual([
      "ER48", "Alberta", "15", "19.23", "26", "LFS 2023-24 PR NOC5", "province", "Labour Force Survey", "2023-2024", "hourly", "2025-11-19", "",
    ]);
  });

  it("63210 under Edmonton is another provincial figure from another survey, not a copy of Alberta's row (verifier's note)", () => {
    expect(expected(rowOf(wages.forRegion("63210", "4860")))).toEqual([
      "ER4860", "Edmonton", "15", "17", "22", "EI 2023-24 PR NOC5", "province", "Employment Insurance Survey Data", "2023-2024", "hourly", "2025-11-19", "",
    ]);
  });

  it("21232 Software developers and programmers: Calgary's own figure and Alberta's differ in the low wage", () => {
    expect(expected(rowOf(wages.forRegion("21232", "ER4830")))).toEqual([
      "ER4830", "Calgary", "26", "48.08", "76.92", "LFS 2023-24 ER NOC5", "economic-region", "Labour Force Survey", "2023-2024", "hourly", "2025-11-19", "",
    ]);
    expect(expected(rowOf(wages.forProvince("21232", "AB")))).toEqual([
      "ER48", "Alberta", "29.81", "48.08", "76.92", "LFS 2023-24 PR NOC5", "province", "Labour Force Survey", "2023-2024", "hourly", "2025-11-19", "",
    ]);
  });

  it("a row the government didn't publish comes back as that row, with its note, not as the province's row", () => {
    // Cabinetmakers in Red Deer's region: no figures, and the note pointing to the provincial level.
    const reddeer = rowOf(wages.forRegion("72311", "4850"));
    expect([reddeer.geography.name, reddeer.low, reddeer.median, reddeer.high, reddeer.sourceCode, reddeer.level, reddeer.referencePeriod]).toEqual([
      "Red Deer", null, null, null, "N/A", "not-published", "NA",
    ]);
    expect(reddeer.comment).toBe(
      "Due to data limitations, the wage for this occupation cannot be published. Please refer to the wage published for this occupation at the provincial level.",
    );
  });

  it("a province with no two-digit code of its own is read as the file has it: Prince Edward Island's one code, ER1110", () => {
    expect(wages.wholeProvinceCode("AB")).toBe("ER48");
    expect(Object.fromEntries(wageData.wholeProvince)).toMatchObject({ PEI: "ER1110", YK: "ER6010", NWT: "ER6110", NU: "ER6210", ON: "ER35" });
    expect(rowOf(wages.forProvince("72311", "PEI")).geography).toEqual({ code: "ER1110", kind: "economic-region", province: "PEI", name: "Prince Edward Island" });
  });
});

// ---- Planted files: the level comes from the source code, and missing is missing --------------------

const HEADER = [
  "NOC_CNP", "NOC_Title_eng", "NOC_Title_fra", "prov", "ER_Code_Code_RE", "ER_Name", "Nom_RE", "Low_Wage_Salaire_Minium",
  "Median_Wage_Salaire_Median", "High_Wage_Salaire_Maximal", "Average_Wage_Salaire_Moyen", "Quartile1_Wage_Salaire_Quartile1",
  "Quartile3_Wage_Salaire_Quartile3", "Source2025_NHQ", "Data_Source_E", "Data_Source_F", "Reference_Period", "Revision_Date_Date_revision",
  "Annual_Wage_Flag_Salaire_annuel", "Wage_Comment_E", "Wage_Comment_F", "EmployeesWithNonWageBenefit_Pct",
];
type Planted = { noc: string; prov: string; code: string; name: string; low?: string; median?: string; high?: string; source: string; comment?: string };
/** An invented file in the wage file's shape: a byte-order mark, the 22 columns, "\r\n" line endings. */
const planted = (rows: Planted[]) =>
  "﻿" +
  [
    HEADER.join(","),
    ...rows.map((r) =>
      [
        `NOC_${r.noc}`, "Invented job", "Emploi inventé", r.prov, r.code, r.name, r.name, r.low ?? "", r.median ?? "", r.high ?? "", "", "", "",
        r.source, r.source === "N/A" ? "NA" : "Labour Force Survey", "", r.source === "N/A" ? "NA" : "2023-2024", "2025-11-19", "0",
        r.comment ? `"${r.comment}"` : "", "", "",
      ].join(","),
    ),
  ].join("\r\n") +
  "\r\n";
const lookupOf = (rows: Planted[]) => createWageLookup(readWageFile(planted(rows), { name: "planted.csv" }));

describe("the level comes from the row's source code, never its name", () => {
  it("labels a row named for a region, filed under a region's code, as province when its code says PR", () => {
    const lookup = lookupOf([
      { noc: "99991", prov: "AB", code: "ER48", name: "Alberta", low: "15", median: "19", high: "26", source: "LFS 2023-24 PR NOC5" },
      { noc: "99991", prov: "AB", code: "ER4830", name: "Calgary", low: "15", median: "19", high: "26", source: "LFS 2023-24 PR NOC5" },
      { noc: "99992", prov: "AB", code: "ER4830", name: "Calgary", low: "20", median: "25", high: "30", source: "SAE 2024 ER NOC5" },
      { noc: "99993", prov: "AB", code: "ER4830", name: "Calgary", low: "20", median: "25", high: "30", source: "CIHI 2023-24" },
      { noc: "99994", prov: "AB", code: "ER4830", name: "Calgary", low: "20", median: "25", high: "30", source: "LFS 2023-24 ATL NOC5" },
    ]);
    expect(rowOf(lookup.forRegion("99991", "4830")).level).toBe("province");
    expect(rowOf(lookup.forRegion("99992", "4830")).level).toBe("economic-region");
    expect(rowOf(lookup.forRegion("99993", "4830")).level).toBe("not-stated");
    expect(rowOf(lookup.forRegion("99994", "4830")).level).toBe("not-stated");
  });

  it("gives the same level whatever the region is called", () => {
    const named = (name: string) => rowOf(lookupOf([{ noc: "99991", prov: "AB", code: "ER4830", name, low: "1", median: "2", high: "3", source: "EI 2023-24 PR NOC5" }]).forRegion("99991", "4830"));
    for (const name of ["Calgary", "Alberta", "Canada", "Economic region"]) expect(named(name).level).toBe("province");
  });

  it("reads every committed row's level from its code alone", () => {
    expect(levelOfSourceCode("LFS 2023-24 CAN NOC5")).toBe("national");
    expect(levelOfSourceCode("JUDGE PR 2024 NOC5")).toBe("province");
    expect(levelOfSourceCode("Census 2021 ER NOC5")).toBe("economic-region");
    expect(levelOfSourceCode("N/A")).toBe("not-published");
    expect(() => levelOfSourceCode("LFS 2023-24 PR ER NOC5")).toThrow(/more than one level/);
    // Every source code in the 2025 file, and the level its token gives it.
    expect(Object.fromEntries(wageData.sourceCodes.map((code) => [code, levelOfSourceCode(code)]))).toEqual({
      "N/A": "not-published",
      "Census 2021 CAN NOC5": "national",
      "LFS 2023-24 CAN NOC5": "national",
      "EI 2023-24 CAN NOC5": "national",
      "SAE 2024 CAN NOC5": "national",
      "LFS 2023-24 PR NOC5": "province",
      "EI 2023-24 PR NOC5": "province",
      "SAE 2024 PR NOC5": "province",
      "Census 2021 PR NOC5": "province",
      "JUDGE PR 2024 NOC5": "province",
      "LFS 2023-24 ER NOC5": "economic-region",
      "EI 2023-24 ER NOC5": "economic-region",
      "SAE 2024 ER NOC5": "economic-region",
      "Census 2021 ER NOC5": "economic-region",
      "LFS 2023-24 ATL NOC5": "not-stated",
      "CIHI 2023-24": "not-stated",
      "JUDGE 2024": "not-stated",
      "Yukon 2023-24": "not-stated",
    });
  });
});

describe("a missing combination comes back as missing, never as a neighbour's row", () => {
  const lookup = lookupOf([
    { noc: "99991", prov: "AB", code: "ER48", name: "Alberta", low: "15", median: "19", high: "26", source: "LFS 2023-24 PR NOC5" },
    { noc: "99991", prov: "AB", code: "ER4820", name: "Camrose--Drumheller", low: "14", median: "18", high: "25", source: "SAE 2024 ER NOC5" },
    { noc: "99992", prov: "AB", code: "ER4830", name: "Calgary", low: "20", median: "25", high: "30", source: "LFS 2023-24 ER NOC5" },
  ]);

  it("has no row for 99991 in Calgary's region, and says so, though Alberta's and the next region's rows exist", () => {
    expect(lookup.forRegion("99991", "4830")).toEqual({
      found: false,
      noc: "99991",
      geography: "ER4830",
      missing: "The wage file has no row for job group 99991 in ER4830.",
    });
  });

  it("has no row for a job group the file doesn't list, or a place it doesn't have", () => {
    expect(lookup.forRegion("99999", "4830").found).toBe(false);
    expect(lookup.forProvince("99992", "AB").found).toBe(false);
    expect(lookup.forProvince("99991", "BC")).toEqual({ found: false, noc: "99991", geography: "BC", missing: "The wage file has no row for BC as a whole." });
    expect(wages.forRegion("72311", "4899").found).toBe(false);
    expect(wages.forProvince("72311", "YT").found).toBe(false); // the file spells Yukon "YK"
  });

  it("refuses a key of the wrong shape rather than guess (an OaSIS profile code, a province code as a region)", () => {
    expect(() => wages.forRegion("72311.00", "4830")).toThrow(/five-digit NOC/);
    expect(() => wages.forRegion("72311", "48")).toThrow(/four-digit code/);
  });
});

describe("wages only: no outlook, average, quartile or benefit field", () => {
  it("has none in the module or in a row a look-up gives", () => {
    const text = read(WAGE_MODULE_PATH);
    expect(text).not.toMatch(/outlook|average|quartile|benefit/i);
    expect(Object.keys(wageData).sort()).toEqual(["comments", "file", "geographies", "methods", "periods", "revisionDates", "rows", "sourceCodes", "wholeProvince"]);
    expect(Object.keys(rowOf(wages.forRegion("72311", "4830"))).sort()).toEqual([
      "basis", "comment", "geography", "high", "level", "low", "median", "method", "noc", "referencePeriod", "revisionDate", "sourceCode",
    ]);
  });

  it("keeps each figure as the file's own text, so nothing adds it up by accident", () => {
    for (const row of wageData.rows.slice(0, 2000)) for (const figure of [row[2], row[3], row[4]]) expect(figure === null || typeof figure === "string").toBe(true);
  });
});

describe("the import's refusals", () => {
  const good = () => planted([{ noc: "99991", prov: "AB", code: "ER48", name: "Alberta", low: "1", median: "2", high: "3", source: "LFS 2023-24 PR NOC5" }]);

  it("refuses a file without its byte-order mark", () => {
    expect(() => readWageFile(good().slice(1), { name: "planted.csv" })).toThrow(/planted\.csv should be UTF-8 with a byte-order mark/);
  });

  it("refuses a row marked N/A that has figures, a figure that isn't a number, and a second row for one place", () => {
    const row = { noc: "99991", prov: "AB", code: "ER48", name: "Alberta", source: "N/A" };
    expect(() => readWageFile(planted([{ ...row, median: "19" }]))).toThrow(/marked N\/A but has figures/);
    expect(() => readWageFile(planted([{ ...row, source: "LFS 2023-24 PR NOC5", median: "$19" }]))).toThrow(/"\$19" isn't a figure/);
    expect(() => readWageFile(planted([row, row]))).toThrow(/a second row for ER48/);
  });

  it("refuses a geography code given two names", () => {
    expect(() =>
      readWageFile(
        planted([
          { noc: "99991", prov: "AB", code: "ER4830", name: "Calgary", source: "N/A" },
          { noc: "99992", prov: "AB", code: "ER4830", name: "Edmonton", source: "N/A" },
        ]),
      ),
    ).toThrow(/ER4830 is "AB, Edmonton" here and "AB, Calgary" earlier/);
  });
});

// ---- --download, against a stand-in for open.canada.ca ----------------------------------------------

describe("--download keeps the file only when it is the pinned one, in its encoding", () => {
  let scratch = "";
  afterEach(() => {
    vi.unstubAllGlobals();
    if (scratch) rmSync(scratch, { recursive: true, force: true });
    scratch = "";
  });
  const makeRoot = () => {
    scratch = mkdtempSync(path.join(os.tmpdir(), "wages-download-"));
    mkdirSync(path.join(scratch, path.dirname(WAGE_MODULE_PATH)), { recursive: true });
    return scratch;
  };
  const committedBytes = () => readFileSync(path.join(root, WAGE_DATA_DIR, FILE.name));
  const serve = (bytes: Buffer) => vi.stubGlobal("fetch", async (url: string) => (url === FILE.url ? new Response(new Uint8Array(bytes)) : new Response("not found", { status: 404 })));
  const run = async (dir: string) => {
    const lines: string[] = [];
    const code = await main(["--download"], { root: dir, log: (line) => lines.push(line) });
    return { code, said: lines.join("\n") };
  };
  const written = (dir: string) => (existsSync(path.join(dir, WAGE_DATA_DIR)) ? readdirSync(path.join(dir, WAGE_DATA_DIR)) : []);

  it("writes the file as the server sent it, then rebuilds the same module", async () => {
    const dir = makeRoot();
    serve(committedBytes());
    const { code, said } = await run(dir);
    expect(code).toBe(0);
    expect(said).toContain(`downloaded ${FILE.name}`);
    expect(readFileSync(path.join(dir, WAGE_DATA_DIR, FILE.name)).equals(committedBytes())).toBe(true);
    expect(readFileSync(path.join(dir, WAGE_MODULE_PATH), "utf8")).toBe(read(WAGE_MODULE_PATH).replace(/\r\n/g, "\n"));
  });

  it("writes nothing when one figure differs, and says what it expected and what it got", async () => {
    const dir = makeRoot();
    const altered = Buffer.from(committedBytes().toString("utf8").replace(",ER4830,Calgary,Calgary,18,23,30,", ",ER4830,Calgary,Calgary,18,24,30,"), "utf8");
    expect(altered.equals(committedBytes())).toBe(false);
    serve(altered);
    const { code, said } = await run(dir);
    expect(code).toBe(1);
    expect(written(dir)).toEqual([]);
    expect(existsSync(path.join(dir, WAGE_MODULE_PATH))).toBe(false);
    expect(said).toContain(`expected ${FILE.sha256}`);
    expect(said).toContain("Nothing was rebuilt.");
  });

  it("writes nothing when the file comes in another encoding (Latin-1)", async () => {
    const dir = makeRoot();
    serve(Buffer.from(committedBytes().toString("utf8").replace(/^﻿/, ""), "latin1"));
    const { code, said } = await run(dir);
    expect(code).toBe(1);
    expect(written(dir)).toEqual([]);
    expect(said).toContain(`${FILE.name} is declared UTF-8 but isn't valid UTF-8`);
  });

  it("rebuilds nothing from a copy that lost its byte-order mark", async () => {
    const dir = makeRoot();
    serve(committedBytes().subarray(3));
    const { code, said } = await run(dir);
    expect(code).toBe(1);
    expect(existsSync(path.join(dir, WAGE_MODULE_PATH))).toBe(false);
    expect(said).toContain("should be UTF-8 with a byte-order mark, and has no byte-order mark");
  });
});
