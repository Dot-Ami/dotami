/**
 * The OaSIS "Example Titles" import (task 28a; research note 28f): `scripts/import-oasis-titles.mjs` turns the
 * government's example job titles, committed as downloaded under data/oasis-2025-v1.0/, into
 * lib/engines/oasis/v2026/titles.ts, the titles "What's closest to your work?" searches. These tests redo the
 * import on every run and refuse a module that isn't exactly what the file makes.
 */
import { createHash } from "node:crypto";
import { existsSync, mkdirSync, mkdtempSync, readdirSync, readFileSync, rmSync } from "node:fs";
import os from "node:os";
import path from "node:path";
import { afterEach, describe, expect, it, vi } from "vitest";

import { oasisData } from "@/lib/engines/oasis/v2026/data";
import { oasisTitles } from "@/lib/engines/oasis/v2026/titles";

import { evenText } from "../scripts/lib/import-kit.mjs";
import {
  buildOasisTitlesModule,
  main,
  OASIS_TITLES_DATA_DIR,
  OASIS_TITLES_FILES,
  OASIS_TITLES_MODULE_PATH,
} from "../scripts/import-oasis-titles.mjs";

const root = process.cwd();
const read = (rel: string) => readFileSync(path.join(root, rel), "utf8");
const FILE = OASIS_TITLES_FILES[0]!;
const committed = () => read(path.join(OASIS_TITLES_DATA_DIR, FILE.name));

describe("the import can be redone", () => {
  it("turns the committed file into the committed module, byte for byte", () => {
    expect(buildOasisTitlesModule({ titles: committed() })).toBe(read(OASIS_TITLES_MODULE_PATH).replace(/\r\n/g, "\n"));
  });

  it("reads the Example Titles file of the OaSIS 2025 dataset on open.canada.ca", () => {
    expect(FILE.name).toBe("example-titles_oasis_2025_v1.0.csv");
    expect(FILE.url).toMatch(/^https:\/\/open\.canada\.ca\/data\/dataset\/10ce43bd-fb58-4969-806b-4bffebc87bec\/resource\/[0-9a-f-]+\/download\//);
    expect(FILE.url.endsWith(`/${FILE.name}`)).toBe(true);
  });

  it("pins the file's SHA-256, of its text with the line endings evened out, and the module records the same", () => {
    const sha = createHash("sha256").update(evenText(committed()), "utf8").digest("hex");
    expect(FILE.sha256).toBe(sha);
    expect(oasisTitles.files).toEqual([{ name: FILE.name, sha256: sha }]);
  });

  it("keeps every row of the file: 18,666 titles of the three types, for every one of the 900 jobs", () => {
    expect(oasisTitles.titles).toHaveLength(18666);
    const types = new Map<string, number>();
    for (const [, type] of oasisTitles.titles) types.set(type, (types.get(type) ?? 0) + 1);
    expect(Object.fromEntries(types)).toEqual({ Example: 4279, Index: 14235, Inclusion: 152 });
    const jobs = new Set(oasisData.occupations.map(([code]) => code));
    const titled = new Set(oasisTitles.titles.map(([code]) => code));
    // Every title belongs to a job the skills list knows, and every job has titles.
    expect([...titled].filter((code) => !jobs.has(code))).toEqual([]);
    expect([...jobs].filter((code) => !titled.has(code))).toEqual([]);
  });

  it("keeps each title word for word, as the research saw them (barber for Barbers, hairstylist for Hairstylists)", () => {
    const of = (code: string) => oasisTitles.titles.filter(([c]) => c === code).map(([, type, title]) => `${type}: ${title}`);
    expect(of("63210.02")).toEqual(["Example: barber apprentice", "Example: barber"]);
    expect(of("63210.01")).toContain("Example: hairstylist");
    expect(of("44100.01")).toContain("Index: home child care provider");
    for (const [, , title] of oasisTitles.titles) expect(title.trim()).toBe(title);
  });

  it("starts with the licence's attribution line and says it is generated", () => {
    const text = read(OASIS_TITLES_MODULE_PATH);
    expect(text.split(/\r?\n/)[0]).toBe("// Contains information licensed under the Open Government Licence – Canada.");
    expect(text).toContain("Generated by scripts/import-oasis-titles.mjs");
  });
});

describe("the import's own rules, on tiny invented files", () => {
  const header = "﻿OaSIS profile code,Concordance number,Job title type,Job title text";

  it("keeps a quoted title with a comma in it, and trims the spaces at its ends", () => {
    const made = buildOasisTitlesModule({ titles: `${header}\r\n72311.00,1,Example,"cabinetmaker, custom "\r\n` });
    expect(made).toContain('["72311.00", "Example", "cabinetmaker, custom"],');
  });

  it("refuses another header, a code that isn't a job code, a type it doesn't know, and an empty title", () => {
    expect(() => buildOasisTitlesModule({ titles: "code,number,type,title\n72311.00,1,Example,x\n" })).toThrow(/the header is/);
    expect(() => buildOasisTitlesModule({ titles: `${header}\n72311,1,Example,cabinetmaker\n` })).toThrow(/isn't a job code/);
    expect(() => buildOasisTitlesModule({ titles: `${header}\n72311.00,1,Alias,cabinetmaker\n` })).toThrow(/title type "Alias"/);
    expect(() => buildOasisTitlesModule({ titles: `${header}\n72311.00,1,Example,  \n` })).toThrow(/the title is empty/);
  });
});

describe("--download keeps the file only when its fingerprint is the pinned one", () => {
  let scratch = "";
  afterEach(() => {
    vi.unstubAllGlobals();
    if (scratch) rmSync(scratch, { recursive: true, force: true });
    scratch = "";
  });
  const makeRoot = () => {
    scratch = mkdtempSync(path.join(os.tmpdir(), "oasis-titles-download-"));
    mkdirSync(path.join(scratch, path.dirname(OASIS_TITLES_MODULE_PATH)), { recursive: true });
    return scratch;
  };
  const serve = (bytes: Buffer) =>
    vi.stubGlobal("fetch", async (url: string) => (url === FILE.url ? new Response(new Uint8Array(bytes)) : new Response("not found", { status: 404 })));
  const run = async (dir: string) => {
    const lines: string[] = [];
    const code = await main(["--download"], { root: dir, log: (line) => lines.push(line) });
    return { code, said: lines.join("\n") };
  };
  const bytes = () => readFileSync(path.join(root, OASIS_TITLES_DATA_DIR, FILE.name));

  it("writes the file as the server sent it when it matches, then rebuilds the same module", async () => {
    const dir = makeRoot();
    serve(bytes());
    const { code, said } = await run(dir);
    expect(code).toBe(0);
    expect(said).toContain(`downloaded ${FILE.name}`);
    expect(readFileSync(path.join(dir, OASIS_TITLES_MODULE_PATH), "utf8")).toBe(read(OASIS_TITLES_MODULE_PATH).replace(/\r\n/g, "\n"));
  });

  it("writes nothing when one title differs, and says what it expected and what it got", async () => {
    const dir = makeRoot();
    serve(Buffer.from(bytes().toString("utf8").replace("63210.02,2,Example,barber", "63210.02,2,Example,barbers"), "utf8"));
    const { code, said } = await run(dir);
    expect(code).toBe(1);
    const data = path.join(dir, OASIS_TITLES_DATA_DIR);
    expect(existsSync(data) ? readdirSync(data) : []).toEqual([]);
    expect(said).toContain(`expected ${FILE.sha256}`);
    expect(said).toContain("Nothing was rebuilt.");
  });
});
